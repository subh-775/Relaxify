/**
 * Writes the Android vector drawables that carry the app's icon set outside
 * the React Native view tree: the home-screen widget's buttons and the media
 * notification's. They are drawn from src/glyphs.ts, the same data the app
 * draws its icons from, so the three can never disagree.
 *
 *   node --no-warnings scripts/icons.js
 *
 * (Node 22.18+ reads glyphs.ts as it stands, stripping its types.) Run it after changing a
 * transport glyph, and commit what it writes.
 */
const {writeFileSync} = require('node:fs');
const {join} = require('node:path');

// Run from the repository root, like the other scripts.
const RES = join(process.cwd(), 'android/app/src/main/res/drawable');

function vector({STROKE, partsOf}, name, color) {
  const paths = partsOf(name, false).map(p => {
    const fill = p.mode === 'fill' || p.mode === 'both';
    const stroke = p.mode !== 'fill';
    const attrs = [`android:pathData="${p.d}"`];
    if (fill) {
      attrs.push(`android:fillColor="${color}"`, 'android:fillType="evenOdd"');
    }
    if (stroke) {
      attrs.push(
        `android:strokeColor="${color}"`,
        `android:strokeWidth="${STROKE * (p.w ?? 1)}"`,
        `android:strokeLineCap="${p.cap ?? 'butt'}"`,
        `android:strokeLineJoin="${p.join ?? 'round'}"`,
      );
    }
    return `    <path\n        ${attrs.join('\n        ')} />`;
  });
  return (
    '<?xml version="1.0" encoding="utf-8"?>\n' +
    `<!-- Generated by scripts/icons.js from src/glyphs.ts (${name}). -->\n` +
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n' +
    '    android:width="24dp" android:height="24dp"\n' +
    '    android:viewportWidth="24" android:viewportHeight="24">\n' +
    `${paths.join('\n')}\n</vector>\n`
  );
}

// The widget's colour for each: play/pause sit on its white disc, so black;
// prev/next sit on the song-tinted card, so white.
const TRANSPORT = [
  ['play', 'Play', '#FF000000'],
  ['pause', 'Pause', '#FF000000'],
  ['next', 'SkipForward', '#FFFFFFFF'],
  ['prev', 'SkipBack', '#FFFFFFFF'],
];

// glyphs.ts is an ES module in TypeScript; Node strips its types on import.
import('../src/glyphs.ts').then(g => {
  for (const [file, glyph, widgetColor] of TRANSPORT) {
    writeFileSync(join(RES, `ic_widget_${file}.xml`), vector(g, glyph, widgetColor));
    // The notification's: white, the colour Android expects before it tints.
    writeFileSync(join(RES, `ic_notif_${file}.xml`), vector(g, glyph, '#FFFFFFFF'));
  }
  console.log('wrote', TRANSPORT.length * 2, 'drawables');
});
